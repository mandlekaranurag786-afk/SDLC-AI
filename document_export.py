import os
import re
from datetime import datetime
from pathlib import Path

from docx import Document
from docx.enum.text import WD_BREAK
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Inches, Pt

from post_processor import add_cover_warning_banner, render_markdown_table, scan_placeholders, strip_chatty_closings


OUTPUT_DIR = Path(os.getenv("DOCX_OUTPUT_DIR", "generated_docs"))
DOCUMENT_TITLES = {
    "estimation": "Project Estimation Report",
    "epics_stories": "Epics & User Stories",
}
DOCUMENT_FILE_SUFFIXES = {
    "estimation": "Project_Estimation",
    "epics_stories": "Epics_Stories",
}


def export_documents(
    *,
    session_id: str,
    project_name: str,
    brd_markdown: str,
    frd_markdown: str,
    validation_report: dict | None = None,
) -> tuple[str, str]:
    session_dir = OUTPUT_DIR / session_id
    session_dir.mkdir(parents=True, exist_ok=True)
    brd_path = session_dir / "BRD.docx"
    frd_path = session_dir / "FRD.docx"
    traceability = extract_traceability(frd_markdown)

    build_docx(
        title="Business Requirement Document",
        project_name=project_name,
        markdown=brd_markdown,
        output_path=brd_path,
        traceability=[],
        include_traceability=False,
        validation_report=validation_report,
    )
    build_docx(
        title="Functional Requirement Document",
        project_name=project_name,
        markdown=frd_markdown,
        output_path=frd_path,
        traceability=traceability,
        include_traceability=True,
        validation_report=validation_report,
    )
    return str(brd_path), str(frd_path)


def export_single_document(
    session_id: str,
    project_name: str,
    markdown_content: str,
    doc_type: str,
) -> str:
    session_dir = OUTPUT_DIR / session_id
    session_dir.mkdir(parents=True, exist_ok=True)
    file_suffix = DOCUMENT_FILE_SUFFIXES.get(doc_type, doc_type.replace("_", " ").title())
    output_path = session_dir / f"{file_suffix}.docx"
    title = DOCUMENT_TITLES.get(doc_type, doc_type.replace("_", " ").title())
    build_docx(
        title=title,
        project_name=project_name,
        markdown=markdown_content,
        output_path=output_path,
        traceability=[],
        include_traceability=False,
    )
    return str(output_path)


def build_docx(
    *,
    title: str,
    project_name: str,
    markdown: str,
    output_path: Path,
    traceability: list[tuple[str, str]],
    include_traceability: bool = True,
    validation_report: dict | None = None,
) -> None:
    if validation_report is None:
        validation_report = {"issues": []}
    elif "issues" not in validation_report:
        validation_report["issues"] = []

    markdown = strip_chatty_closings(markdown)
    # Run deterministic post-processing check for placeholder leakage
    placeholder_issues = scan_placeholders(markdown, doc_name=title)
    validation_report["issues"].extend(placeholder_issues)

    document = Document()
    configure_document(document, title=title, project_name=project_name)
    add_title_page(document, title=title, project_name=project_name, validation_report=validation_report)
    add_toc(document)
    if include_traceability and traceability:
        add_summary_page(document, traceability)
    render_markdown(document, markdown)
    add_open_items_appendix(document, validation_report)
    document.save(output_path)


def configure_document(document: Document, *, title: str, project_name: str) -> None:
    section = document.sections[0]
    section.top_margin = Inches(0.8)
    section.bottom_margin = Inches(0.8)
    section.left_margin = Inches(0.8)
    section.right_margin = Inches(0.8)

    styles = document.styles
    styles["Normal"].font.name = "Aptos"
    styles["Normal"].font.size = Pt(10.5)
    for style_name in ["Title", "Heading 1", "Heading 2", "Heading 3"]:
        styles[style_name].font.name = "Aptos Display"

    footer = section.footer.paragraphs[0]
    footer.text = f"{project_name} | {title} | Page "
    add_page_number(footer)


def add_title_page(
    document: Document,
    *,
    title: str,
    project_name: str,
    validation_report: dict | None = None,
) -> None:
    document.core_properties.title = title
    document.core_properties.subject = project_name
    document.core_properties.author = "SDLC AI"
    document.core_properties.version = "1.0"

    document.add_heading(project_name, level=0)
    document.add_heading(title, level=1)
    
    # Inject cover warning banner if unresolved issues exist
    add_cover_warning_banner(document, validation_report)

    document.add_paragraph("Version: 1.0")
    document.add_paragraph(f"Generated Date: {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}")
    document.add_paragraph("Generated by: SDLC AI BRD/FRD Generation Agent")
    document.add_page_break()


def add_toc(document: Document) -> None:
    document.add_heading("Table of Contents", level=1)
    paragraph = document.add_paragraph()
    run = paragraph.add_run()
    fld_char = OxmlElement("w:fldChar")
    fld_char.set(qn("w:fldCharType"), "begin")
    instr_text = OxmlElement("w:instrText")
    instr_text.set(qn("xml:space"), "preserve")
    instr_text.text = 'TOC \\o "1-3" \\h \\z \\u'
    fld_char2 = OxmlElement("w:fldChar")
    fld_char2.set(qn("w:fldCharType"), "separate")
    fld_char3 = OxmlElement("w:fldChar")
    fld_char3.set(qn("w:fldCharType"), "end")
    run._r.append(fld_char)
    run._r.append(instr_text)
    run._r.append(fld_char2)
    run._r.append(fld_char3)
    document.add_paragraph("Update this field in Microsoft Word to refresh page numbers.")
    document.add_page_break()


def add_summary_page(document: Document, traceability: list[tuple[str, str]]) -> None:
    document.add_heading("Traceability Summary", level=1)
    table = document.add_table(rows=1, cols=2)
    table.style = "Table Grid"
    table.rows[0].cells[0].text = "BRD Item"
    table.rows[0].cells[1].text = "FRD Requirement"
    if traceability:
        for fr_id, brd_section in traceability:
            cells = table.add_row().cells
            cells[0].text = brd_section
            cells[1].text = fr_id
    else:
        cells = table.add_row().cells
        cells[0].text = "TBD"
        cells[1].text = "TBD"
    document.add_page_break()


def add_open_items_appendix(document: Document, validation_report: dict | None) -> None:
    if not validation_report:
        return
    issues = validation_report.get("issues") or []
    if not issues:
        return

    document.add_page_break()
    document.add_heading("Appendix: Open Items for Review", level=1)
    document.add_paragraph(
        "The following items were flagged during automated validation. They do not block this document from being used, "
        "but should be reviewed before final sign-off."
    )
    for issue in issues:
        paragraph = document.add_paragraph(style="List Bullet")
        severity = issue.get("severity", "TBD")
        section = issue.get("section", "TBD")
        affected_requirement = issue.get("affected_requirement", "TBD")
        recommendation = issue.get("recommendation", "Review and refine this item.")
        paragraph.add_run(f"[{severity}] {section}: ").bold = True
        paragraph.add_run(f"{affected_requirement} - {recommendation}")


def render_markdown(document: Document, markdown: str) -> None:
    lines = markdown.splitlines()
    i = 0
    while i < len(lines):
        raw_line = lines[i]
        line = raw_line.strip()
        if not line:
            i += 1
            continue

        # Check for markdown table block
        if line.startswith("|") and line.endswith("|"):
            table_block = []
            while i < len(lines) and lines[i].strip().startswith("|") and lines[i].strip().endswith("|"):
                table_block.append(lines[i].strip())
                i += 1
            render_markdown_table(document, table_block)
            continue

        if line == "---":
            paragraph = document.add_paragraph()
            paragraph.add_run().add_break(WD_BREAK.LINE)
        elif line.startswith("### "):
            document.add_heading(line[4:], level=3)
        elif line.startswith("## "):
            document.add_heading(line[3:], level=2)
        elif line.startswith("# "):
            document.add_heading(line[2:], level=1)
        elif re.match(r"^\d+\.\s+", line):
            document.add_paragraph(re.sub(r"^\d+\.\s+", "", line), style="List Number")
        elif line.startswith("- "):
            document.add_paragraph(line[2:], style="List Bullet")
        elif line.startswith("**") and line.endswith("**"):
            paragraph = document.add_paragraph()
            paragraph.add_run(line.strip("*")).bold = True
        else:
            add_rich_paragraph(document, line)
        i += 1


def add_rich_paragraph(document: Document, line: str) -> None:
    paragraph = document.add_paragraph()
    parts = re.split(r"(\*\*.*?\*\*)", line)
    for part in parts:
        if not part:
            continue
        if part.startswith("**") and part.endswith("**"):
            paragraph.add_run(part[2:-2]).bold = True
        else:
            paragraph.add_run(part)


def add_page_number(paragraph) -> None:
    run = paragraph.add_run()
    fld_char1 = OxmlElement("w:fldChar")
    fld_char1.set(qn("w:fldCharType"), "begin")
    instr_text = OxmlElement("w:instrText")
    instr_text.set(qn("xml:space"), "preserve")
    instr_text.text = "PAGE"
    fld_char2 = OxmlElement("w:fldChar")
    fld_char2.set(qn("w:fldCharType"), "separate")
    fld_char3 = OxmlElement("w:fldChar")
    fld_char3.set(qn("w:fldCharType"), "end")
    run._r.append(fld_char1)
    run._r.append(instr_text)
    run._r.append(fld_char2)
    run._r.append(fld_char3)


def extract_traceability(frd_markdown: str) -> list[tuple[str, str]]:
    traceability = []
    pattern = r"\*\*(FR-\d+)\*\*.*?\*\*BRD Mapping:\*\*\s*(BRD Section\s+[\d.]+)"
    for match in re.finditer(pattern, frd_markdown, flags=re.DOTALL):
        fr_id, brd_section = match.groups()
        traceability.append((fr_id, brd_section))
    return traceability
